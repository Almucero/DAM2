namespace Calculadora
{
    public static class CalculadoraEjemplo
    {
        public static int Suma (int item11, int item2)
        {
            return item11 + item2;
        }
        public static int Resta(int item11, int item2)
        {
            return item11 - item2;
        }
        public static int Multiplicacion(int item11, int item2)
        {
            return item11 * item2;
        }
        public static double Division(int item11, int item2)
        {
            return item11 / item2;
        }
    }
}
